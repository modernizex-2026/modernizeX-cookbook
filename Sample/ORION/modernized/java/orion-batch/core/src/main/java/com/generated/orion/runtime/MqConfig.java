package com.generated.orion.runtime;

import com.appruntime.MqRunner;
import com.appruntime.MqService;

import org.springframework.beans.factory.ObjectProvider;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jms.core.JmsTemplate;

/**
 * IBM MQ verbs (COBOL CALL 'MQOPEN'/'MQGET'/'MQPUT'/'MQPUT1'/'MQCLOSE') for this cohort.
 *
 * <p>With a JMS broker on the classpath (the launcher ships spring-boot-starter-activemq; point
 * MQ_BROKER_URL at a real broker) Spring Boot provides a JmsTemplate and the verbs run through
 * {@link MqRunner}. Without one, {@link MqStubService} answers with MQ-level codes so programs take
 * their normal MQ-failure branches instead of crashing. Generated by Cobol2Java.
 */
@Configuration
public class MqConfig {

    @Bean
    public MqService mqService(ObjectProvider<JmsTemplate> jms) {
        JmsTemplate template = jms.getIfAvailable();
        return template != null ? new MqRunner(template) : new MqStubService();
    }
}
